// One-time (re-runnable) export of kidinjurylaw.com from WordPress.com into this repo.
//
// - Posts  -> src/content/posts/<slug>.md  (YAML frontmatter + the original post HTML, untouched
//            except that links/images pointing at the old WordPress hosts become local paths)
// - Pages  -> src/content/pages/<slug>.md
// - Categories, tags, comments -> src/data/*.json
// - Images -> public/wp-content/uploads/... (same paths as on the old site)
// - Raw API responses -> wordpress-export/ (kept for reference)
//
// Re-running keeps any fields added by hand to a post's frontmatter (shortAnswer, faq, description…).
import { mkdir, writeFile, readFile, access } from 'node:fs/promises';
import { dirname } from 'node:path';
import YAML from 'yaml';

const API = 'https://public-api.wordpress.com/wp/v2/sites/kidinjurylaw.com';
const ROOT = new URL('../', import.meta.url).pathname;
const OLD_HOSTS = /^https?:\/\/(?:www\.)?(?:kidinjurylaw\.com|kidinjurylaw\.wordpress\.com|kidinjurylaw\.files\.wordpress\.com|i[0-3]\.wp\.com\/kidinjurylaw\.(?:files\.)?wordpress\.com)/i;
// Fields generated by this script; everything else in an existing file's frontmatter is preserved.
const EXPORT_FIELDS = ['title', 'date', 'modified', 'path', 'wpId', 'categories', 'tags', 'featuredImage', 'excerpt', 'format'];

const exists = (p) => access(p).then(() => true, () => false);

async function getAll(endpoint) {
  const out = [];
  for (let page = 1; ; page++) {
    const res = await fetch(`${API}/${endpoint}${endpoint.includes('?') ? '&' : '?'}per_page=100&page=${page}`);
    if (!res.ok) break;
    const batch = await res.json();
    if (!Array.isArray(batch) || !batch.length) break;
    out.push(...batch);
    if (batch.length < 100) break;
  }
  return out;
}

const decode = (s) =>
  s.replace(/&nbsp;|&#160;/g, ' ')
    .replace(/&#8217;|&rsquo;/g, '’').replace(/&#8216;|&lsquo;/g, '‘')
    .replace(/&#8220;|&ldquo;/g, '“').replace(/&#8221;|&rdquo;/g, '”')
    .replace(/&#8211;|&ndash;/g, '–').replace(/&#8212;|&mdash;/g, '—')
    .replace(/&#8230;|&hellip;/g, '…').replace(/&#038;|&amp;/g, '&')
    .replace(/&#039;|&#39;/g, "'").replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n));

const stripTags = (s) => s.replace(/<[^>]+>/g, '');

// --- wp.me shortlinks -> real URLs ---
const shortCache = new Map();
async function resolveShortlink(url) {
  if (shortCache.has(url)) return shortCache.get(url);
  let target = url;
  try {
    const res = await fetch(url, { redirect: 'manual' });
    target = res.headers.get('location') || url;
  } catch {}
  shortCache.set(url, target);
  return target;
}

// --- images ---
const images = new Map(); // local path -> remote URL
function localizeImage(url) {
  const m = url.match(/\/wp-content\/uploads\/[^?#"'\s]+|\/(\d{4}\/\d{2}\/[^?#"'\s]+\.(?:jpe?g|png|gif|webp))/i);
  if (!m) return null;
  const path = m[0].startsWith('/wp-content/') ? m[0] : `/wp-content/uploads/${m[1]}`;
  const remote = `https://kidinjurylaw.wordpress.com${path}`;
  images.set(decodeURI(path), remote);
  return path;
}

async function rewriteHtml(html) {
  let out = html;
  // Drop WordPress.com image metadata attributes that point back at the old host or its CDN sizes.
  out = out.replace(/\s(?:srcset|sizes|data-[a-z-]+)="[^"]*"/g, '');
  // wp.me shortlinks
  for (const m of new Set(out.match(/https?:\/\/wp\.me\/[A-Za-z0-9-]+/g) || [])) {
    out = out.split(m).join(await resolveShortlink(m));
  }
  // href/src on the old hosts -> local
  out = out.replace(/(href|src)="([^"]+)"/g, (all, attr, url) => {
    const u = decode(url);
    if (!OLD_HOSTS.test(u)) return all;
    if (/\.(?:jpe?g|png|gif|webp)(?:\?|$)/i.test(u)) {
      const local = localizeImage(u);
      if (local) return `${attr}="${local}"`;
    }
    const path = u.replace(OLD_HOSTS, '').replace(/^\/?/, '/') || '/';
    return `${attr}="${path}"`;
  });
  return out;
}

const pathOf = (link) => new URL(link).pathname;

async function writeEntry(file, fields, body) {
  let existing = {};
  if (await exists(file)) {
    const prev = await readFile(file, 'utf8');
    const fm = prev.match(/^---\n([\s\S]*?)\n---\n/);
    if (fm) existing = YAML.parse(fm[1]) || {};
  }
  const kept = Object.fromEntries(Object.entries(existing).filter(([k]) => !EXPORT_FIELDS.includes(k)));
  const data = { ...fields, ...kept };
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, `---\n${YAML.stringify(data, { lineWidth: 0 })}---\n${body.trim()}\n`);
}

// ---------------------------------------------------------------------------
const [posts, pages, categories, tags, comments] = await Promise.all([
  getAll('posts?status=publish'), getAll('pages'), getAll('categories'), getAll('tags'), getAll('comments'),
]);
console.log(`posts ${posts.length}, pages ${pages.length}, categories ${categories.length}, tags ${tags.length}, comments ${comments.length}`);

await mkdir(`${ROOT}wordpress-export`, { recursive: true });
for (const [name, data] of Object.entries({ posts, pages, categories, tags, comments })) {
  await writeFile(`${ROOT}wordpress-export/${name}.json`, JSON.stringify(data, null, 2));
}

const catSlug = Object.fromEntries(categories.map((c) => [c.id, c.slug]));
const tagSlug = Object.fromEntries(tags.map((t) => [t.id, t.slug]));

for (const p of posts) {
  const body = await rewriteHtml(p.content.rendered);
  const featured = p.jetpack_featured_media_url ? localizeImage(p.jetpack_featured_media_url) : null;
  await writeEntry(`${ROOT}src/content/posts/${p.slug}.md`, {
    title: decode(p.title.rendered),
    date: p.date_gmt + 'Z',
    modified: p.modified_gmt + 'Z',
    path: pathOf(p.link),
    wpId: p.id,
    categories: p.categories.map((id) => catSlug[id]).filter(Boolean),
    tags: p.tags.map((id) => tagSlug[id]).filter(Boolean),
    ...(featured ? { featuredImage: featured } : {}),
    excerpt: decode(stripTags(p.excerpt.rendered)).replace(/\s+/g, ' ').trim(),
    format: 'html',
  }, body);
}

for (const p of pages) {
  await writeEntry(`${ROOT}src/content/pages/${p.slug}.md`, {
    title: decode(p.title.rendered),
    date: p.date_gmt + 'Z',
    modified: p.modified_gmt + 'Z',
    path: pathOf(p.link),
    wpId: p.id,
    format: 'html',
  }, await rewriteHtml(p.content.rendered));
}

await writeFile(`${ROOT}src/data/categories.json`, JSON.stringify(
  categories.map((c) => ({ slug: c.slug, name: decode(c.name), description: decode(stripTags(c.description || '')).trim() })), null, 2));
await writeFile(`${ROOT}src/data/tags.json`, JSON.stringify(
  tags.map((t) => ({ slug: t.slug, name: decode(t.name) })), null, 2));
await writeFile(`${ROOT}src/data/comments.json`, JSON.stringify(
  await Promise.all(comments
    .filter((c) => c.status === 'approved' || !c.status)
    .sort((a, b) => a.date_gmt.localeCompare(b.date_gmt))
    .map(async (c) => ({
      id: c.id, postId: c.post, parent: c.parent, author: decode(c.author_name), date: c.date_gmt + 'Z',
      html: await rewriteHtml(c.content.rendered),
    }))), null, 2));

// Download images (skip ones already present).
let downloaded = 0;
for (const [path, remote] of images) {
  const dest = `${ROOT}public${path}`;
  if (await exists(dest)) continue;
  const res = await fetch(remote);
  if (!res.ok) { console.warn(`! image ${res.status}: ${remote}`); continue; }
  await mkdir(dirname(dest), { recursive: true });
  await writeFile(dest, Buffer.from(await res.arrayBuffer()));
  downloaded++;
}
console.log(`images: ${images.size} referenced, ${downloaded} downloaded; shortlinks resolved: ${shortCache.size}`);
